def _extract_logos_from_reasoning(reasoning: str) -> list[str]:
    """Pull logo/brand names from GPU reasoning text."""
    low = reasoning.lower()
    found: list[str] = []
    seen: set[str] = set()
    for keyword, label in _LOGO_KEYWORDS:
        if keyword in low and label not in seen:
            found.append(label)
            seen.add(label)
    return found


def _screenshots_dir() -> Path:
    d = get_settings().resolved_data_dir / "screenshots"
    d.mkdir(parents=True, exist_ok=True)
    return d


@router.post("/scan-frames/{video_id}")
async def scan_frames(
    video_id: str,
    request_id: RequestIdDep,
    _user: RequireAnalyst,
    videos: VideosRepoDep,
) -> dict:
    """Scan extracted frames of a video through GPU vision model for logo/element detection."""
    import httpx
    import shutil

    s = get_settings()
    gpu_url = (s.gpu_pipeline_url or "").rstrip("/")
    if not gpu_url:
        return {"status": "gpu_required", "video_id": video_id, "frames": [],
                "error": "GPU pipeline not configured", "request_id": request_id}

    # Find frames directory
    frames_dir = s.resolved_data_dir / "frames" / video_id
    if not frames_dir.is_dir():
        return {"status": "no_frames", "video_id": video_id, "frames": [],
                "error": f"No extracted frames found for {video_id}", "request_id": request_id}

    frame_files = sorted(
        [f for f in frames_dir.iterdir() if f.suffix.lower() in (".png", ".jpg", ".jpeg")],
        key=lambda p: p.stat().st_size,
        reverse=True,
    )
    if not frame_files:
        return {"status": "no_frames", "video_id": video_id, "frames": [],
                "error": "No image files in frames directory", "request_id": request_id}

    # Take top 6 frames by file size (most visual content)
    selected = frame_files[:6]
    results: list[dict] = []
    screenshots_saved: list[str] = []
    scr_dir = _screenshots_dir()

    async with httpx.AsyncClient(timeout=90.0) as client:
        for frame_path in selected:
            try:
                file_data = frame_path.read_bytes()
                resp = await client.post(
                    f"{gpu_url}/analyze",
                    files={"file": (frame_path.name, file_data, "image/png")},
                    data={"caption": _FRAME_SCAN_CAPTION, "platform": "logo-detect"},
                )
                if resp.status_code != 200:
                    results.append({
                        "frame": frame_path.name,
                        "status": "error",
                        "reasoning": f"GPU returned {resp.status_code}",
                        "risk_score": 0,
                        "flags": [],
                        "logos_detected": [],
                    })
                    continue
                data = resp.json()
                reasoning = data.get("reasoning", "")
                flags = data.get("flags", [])
                risk = data.get("risk_score", 0)
                logos = _extract_logos_from_reasoning(reasoning)

                # Parse timestamp from frame filename (e.g. f_001440_uniform.png → 1440 frames)
                ts_match = re.search(r'f_(\d+)', frame_path.name)
                timestamp_frame = int(ts_match.group(1)) if ts_match else 0
                timestamp_sec = round(timestamp_frame / 30.0, 1)  # assume ~30fps

                result_entry = {
                    "frame": frame_path.name,
                    "status": "ok",
                    "reasoning": reasoning[:500],
                    "risk_score": risk,
                    "flags": flags,
                    "logos_detected": logos,
                    "timestamp_sec": timestamp_sec,
                    "screenshot_url": None,
                }

                # Save interesting frames as evidence screenshots
                if risk > 0 or logos or flags:
                    dst = scr_dir / f"{video_id}_{frame_path.name}"
                    if not dst.exists():
                        shutil.copy2(str(frame_path), str(dst))
                    result_entry["screenshot_url"] = f"/api/v1/agents/screenshots/{dst.name}"
                    screenshots_saved.append(dst.name)

                results.append(result_entry)

            except Exception as exc:
                logger.warning("scan_frame_error", extra={"frame": frame_path.name}, exc_info=True)
                results.append({
                    "frame": frame_path.name,
                    "status": "error",
                    "reasoning": f"{type(exc).__name__}: {exc}",
                    "risk_score": 0,
                    "flags": [],
                    "logos_detected": [],
                })

    # Get video title
    video = await videos.get(video_id)
    title = (video.title.split("\n")[0][:120] if video and video.title else video_id)

    all_logos = []
    seen: set[str] = set()
    for r in results:
        for l in r.get("logos_detected", []):
            if l not in seen:
                all_logos.append(l)
                seen.add(l)

    return {
        "status": "ok",
        "video_id": video_id,
        "title": title,
        "frames_scanned": len(results),
        "frames": results,
        "all_logos_detected": all_logos,
        "screenshots_saved": screenshots_saved,
        "request_id": request_id,
    }


@router.get("/screenshots/{filename}", response_class=FileResponse)
async def serve_screenshot(filename: str, _user: RequireAnalyst) -> FileResponse:
    """Serve a saved evidence screenshot."""
    scr_dir = _screenshots_dir()
    fpath = scr_dir / filename
    if not fpath.exists() or not fpath.is_file():
        raise HTTPException(status_code=404, detail="Screenshot not found")
    # Prevent path traversal
    if fpath.resolve().parent != scr_dir.resolve():
        raise HTTPException(status_code=403, detail="Access denied")
    return FileResponse(str(fpath), media_type="image/png")


# ── List videos with frames available for scanning ────────────────────────

@router.get("/scannable")
async def list_scannable(
    request_id: RequestIdDep,
    _user: RequireAnalyst,
    videos: VideosRepoDep,
    packages: PackagesRepoDep,
) -> dict:
    """List videos that have extracted frames available for scanning."""
    s = get_settings()
    frames_root = s.resolved_data_dir / "frames"
    if not frames_root.is_dir():
        return {"items": [], "request_id": request_id}

    frame_dirs = [d.name for d in frames_root.iterdir() if d.is_dir()]
    items = []
    for vid in frame_dirs[:50]:
        video = await videos.get(vid)
        if not video:
            continue
        n_frames = len([f for f in (frames_root / vid).iterdir()
                        if f.suffix.lower() in (".png", ".jpg", ".jpeg")])
        if n_frames == 0:
            continue

        # Get risk level
        pkgs = await packages.list_by_video(vid)
        level = None
        score = None
        if pkgs:
            latest = pkgs[-1]
            proj = await packages.get_projection(latest.report_id)
            if proj and proj.get("risk_level"):
                level = proj["risk_level"]
                score = proj["score"]
            else:
                level = latest.risk_level
                score = latest.score

        items.append({
            "video_id": vid,
            "title": (video.title.split("\n")[0][:100] if video.title else vid),
            "platform": video.platform,
            "n_frames": n_frames,
            "level": level,
            "score": round(score, 4) if score is not None else None,
        })

    # Sort: HIGH/CRITICAL first
    level_order = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "LOW": 3}
    items.sort(key=lambda x: (level_order.get(x["level"] or "LOW", 4), -(x["score"] or 0)))

    return {"items": items, "request_id": request_id}


