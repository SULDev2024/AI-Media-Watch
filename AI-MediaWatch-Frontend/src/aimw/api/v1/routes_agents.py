def _parse_detect_response(reasoning: str, score: float | None, url: str) -> dict:
    low = reasoning.lower()

    # Is it AI-generated?
    yes_kw = ["ai-generated", "ai generated", "deepfake", "synthetic", "generated by ai",
               "artificial intelligence", "not real", "digitally created", "yes, this"]
    no_kw  = ["not ai", "real footage", "authentic", "genuine", "not synthetic",
               "not artificially", "appears to be real", "no evidence of ai"]
    is_ai  = any(k in low for k in yes_kw)
    is_real = any(k in low for k in no_kw)

    if is_real and not is_ai:
        is_ai_generated: bool | None = False
        confidence = 0.08
    elif is_ai:
        is_ai_generated = True
        confidence = score or 0.72
    else:
        is_ai_generated = None
        confidence = 0.50

    # Suspected tool + source org
    suspected_tool: str | None = None
    source_org: str | None = None
    if is_ai_generated:
        for kw, tool, org in _TOOL_MAP:
            if kw in low:
                suspected_tool = tool
                source_org = org
                break
        if not suspected_tool:
            suspected_tool = "Unknown Tool"
            source_org = "Unknown Organization"

    # Evidence list
    evidence: list[str] = []
    for kw, desc in _EVIDENCE_MAP:
        if kw in low:
            evidence.append(desc)
    if not evidence and is_ai_generated:
        evidence = ["AI generation artifacts detected — see full reasoning"]

    # Confidence from text like "90%" or "confidence: 0.9"
    pct_matches = re.findall(r'(\d{1,3})\s*%', reasoning)
    if pct_matches:
        try:
            confidence = max(int(p) for p in pct_matches) / 100.0
        except ValueError:
            pass

    return {
        "status": "ok",
        "url": url,
        "is_ai_generated": is_ai_generated,
        "confidence": round(min(confidence, 1.0), 3),
        "suspected_tool": suspected_tool,
        "source_org": source_org,
        "evidence": evidence[:6],
        "full_reasoning": reasoning[:800],
    }


def _extract_yt_id(url: str) -> str | None:
    for pattern in [
        r'youtu\.be/([a-zA-Z0-9_-]{11})',
        r'youtube\.com/watch\?v=([a-zA-Z0-9_-]{11})',
        r'youtube\.com/shorts/([a-zA-Z0-9_-]{11})',
        r'youtube\.com/embed/([a-zA-Z0-9_-]{11})',
    ]:
        m = re.search(pattern, url)
        if m:
            return m.group(1)
    return None


class AIDetectRequest(BaseModel):
    url: str


@router.post("/ai-detect")
async def ai_detect(
    body: AIDetectRequest,
    request_id: RequestIdDep,
    _user: RequireAnalyst,
) -> dict:
    """Submit a URL for AI-generated content / deepfake detection via GPU pipeline."""
    import httpx

    s = get_settings()
    gpu_url = (s.gpu_pipeline_url or "").rstrip("/")
    if not gpu_url:
        return {
            "status": "gpu_required",
            "url": body.url,
            "is_ai_generated": None,
            "confidence": None,
            "suspected_tool": None,
            "source_org": None,
            "evidence": [],
            "full_reasoning": "GPU pipeline not configured. Set AIMW_GPU_PIPELINE_URL to enable AI detection.",
            "request_id": request_id,
        }

    url = body.url.strip()
    target_url = url

    # For YouTube, prefer the high-res thumbnail so vision model gets a clear frame
    yt_id = _extract_yt_id(url)
    if yt_id:
        target_url = f"https://img.youtube.com/vi/{yt_id}/maxresdefault.jpg"

    try:
        async with httpx.AsyncClient(timeout=90.0) as client:
            resp = await client.post(
                f"{gpu_url}/analyze-url",
                data={
                    "video_url": target_url,
                    "caption": _AI_DETECT_CAPTION,
                    "platform": "ai-detect",
                },
            )
            if resp.status_code != 200:
                return {
                    "status": "gpu_offline",
                    "url": url,
                    "is_ai_generated": None,
                    "confidence": None,
                    "suspected_tool": None,
                    "source_org": None,
                    "evidence": [],
                    "full_reasoning": (
                        f"GPU pipeline is unreachable (HTTP {resp.status_code}). "
                        "Ensure the Cloudflare tunnel is running on the GPU server and "
                        "AIMW_GPU_PIPELINE_URL is up to date."
                    ),
                    "request_id": request_id,
                }
            data = resp.json()

        reasoning = (
            data.get("reasoning")
            or data.get("explanation")
            or data.get("verdict", {}).get("reasoning", "")
            or str(data)
        )
        score = data.get("risk_score") or data.get("confidence") or data.get("score")
        if isinstance(score, str):
            try:
                score = float(score)
            except ValueError:
                score = None

        result = _parse_detect_response(reasoning, score, url)
        result["request_id"] = request_id
        return result

    except HTTPException:
        raise
    except Exception as exc:
        logger.warning("ai_detect_error", exc_info=True)
        return {
            "status": "error",
            "url": url,
            "is_ai_generated": None,
            "confidence": None,
            "suspected_tool": None,
            "source_org": None,
            "evidence": [],
            "full_reasoning": f"Detection failed: {type(exc).__name__}: {exc}",
            "request_id": request_id,
        }


# ── Banned sources ────────────────────────────────────────────────────────────

def _banned_path() -> Path:
    return get_settings().resolved_data_dir / _BANNED_FILE


def _load_banned() -> list[dict]:
    p = _banned_path()
    if not p.exists():
        return []
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:
        return []


def _save_banned(items: list[dict]) -> None:
    p = _banned_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(items, indent=2, ensure_ascii=False), encoding="utf-8")


class BanRequest(BaseModel):
    value: str
    type: str = "channel"


# ── Status helpers ────────────────────────────────────────────────────────────

_PHOTO_EXT = {".jpg", ".jpeg", ".png", ".gif", ".webp", ".bmp"}


def _content_type(platform: str, raw_path: str | None) -> str:
    if platform == "manual-image":
        return "photo"
    if platform in ("manual", "manual-text"):
        return "text"
    if raw_path:
        from pathlib import PurePosixPath
        ext = PurePosixPath(raw_path).suffix.lower()
        if ext in _PHOTO_EXT:
            return "photo"
    return "video"


