@router.get("/status")
async def agents_status(
    request_id: RequestIdDep,
    _user: RequireAnalyst,
    videos: VideosRepoDep,
    packages: PackagesRepoDep,
) -> dict:
    try:
        col = control.get_state()
    except Exception:
        col = {"status": "unknown", "enqueued_total": 0, "last_enqueued": 0,
               "queries": [], "platforms": []}

    rows = await videos.list_recent(limit=200)
    total = len(rows)
    analyzed = 0
    by_level = {"CRITICAL": 0, "HIGH": 0, "MEDIUM": 0, "LOW": 0}
    by_action = {"auto_escalate": 0, "analyst_review": 0, "monitor": 0, "suppress": 0}
    total_evidence = 0
    score_sum = 0.0
    recent = []

    for r in rows:
        pkgs = await packages.list_by_video(r.id)
        score = None
        risk_level = None
        action = None
        n_evidence = 0

        if pkgs:
            latest = pkgs[-1]
            proj = await packages.get_projection(latest.report_id)
            if proj is not None and proj.get("risk_level") is not None:
                score = proj["score"]
                risk_level = proj["risk_level"]
                action = proj["action"]
            else:
                score = latest.score
                risk_level = latest.risk_level
            try:
                n_evidence = sum(1 for e in latest.evidence if e.polarity == "incriminating")
            except Exception:
                pass

        if score is not None:
            analyzed += 1
            score_sum += score

        lvl = risk_level or "LOW"
        if lvl in by_level:
            by_level[lvl] += 1
        act = action or "monitor"
        if act in by_action:
            by_action[act] += 1
        total_evidence += n_evidence

        recent.append({
            "video_id": r.id,
            "platform": r.platform,
            "title": (r.title.split("\n")[0][:120] if r.title else None),
            "level": risk_level,
            "score": round(score, 4) if score is not None else None,
            "action": action,
            "collected_at": r.collected_at.isoformat(),
            "content_type": _content_type(r.platform, r.raw_path),
        })

    avg_score = round(score_sum / analyzed, 3) if analyzed > 0 else 0.0
    recent.sort(key=lambda x: (x["score"] or 0.0), reverse=True)
    recent = recent[:30]
    banned = _load_banned()
    s = get_settings()

    return {
        "collector": {
            "status": col.get("status", "unknown"),
            "enqueued_total": col.get("enqueued_total", 0),
            "last_enqueued": col.get("last_enqueued", 0),
            "queries": col.get("queries", []),
            "platforms": col.get("platforms", []),
        },
        "analyst": {
            "total": total,
            "analyzed": analyzed,
            "pending": max(0, total - analyzed),
            "avg_score": avg_score,
            "total_evidence": total_evidence,
        },
        "judge": {
            "verdicts": analyzed,
            "by_level": by_level,
            "by_action": by_action,
        },
        "reporter": {
            "alerts_sent": by_level["CRITICAL"] + by_level["HIGH"],
            "dashboard_items": total,
        },
        "banned_sources": banned,
        "gpu_pipeline": s.gpu_pipeline_url or None,
        "recent_activity": recent,
        "request_id": request_id,
    }


@router.get("/banned")
async def list_banned(request_id: RequestIdDep, _user: RequireAnalyst) -> dict:
    return {"items": _load_banned(), "request_id": request_id}


@router.post("/banned")
async def add_banned(body: BanRequest, request_id: RequestIdDep, _user: RequireAnalyst) -> dict:
    val = body.value.strip()
    if not val:
        raise HTTPException(status_code=422, detail="Empty value")
    items = _load_banned()
    items.append({"value": val, "type": body.type, "banned_at": datetime.now(timezone.utc).isoformat()})
    _save_banned(items)
    return {"items": items, "request_id": request_id}


@router.delete("/banned/{index}")
async def remove_banned(index: int, request_id: RequestIdDep, _user: RequireAnalyst) -> dict:
    items = _load_banned()
    if index < 0 or index >= len(items):
        raise HTTPException(status_code=404, detail="Index out of range")
    items.pop(index)
    _save_banned(items)
    return {"items": items, "request_id": request_id}


